function normalize(value = "") {
  return String(value)
    .toLowerCase()
    .replace(/[_\-\.]/g, " ")
    .replace(/\d+/g, " ")
    .replace(/\b(left|right)\b/g, " ")
    .replace(/\b(l|r)\b/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export function findMuscle(name = "") {
  const n = normalize(name);

  if (!n) return null;

  // Exact / alias matching
  for (const muscle of MUSCLES) {
    const terms = [
      muscle.id,
      muscle.en,
      ...(muscle.aliases || [])
    ].map(normalize);

    if (terms.some(term => term && (n === term || n.includes(term)))) {
      return muscle;
    }
  }

  // Reverse partial matching
  for (const muscle of MUSCLES) {
    const terms = [
      muscle.id,
      muscle.en,
      ...(muscle.aliases || [])
    ].map(normalize);

    if (terms.some(term => term && term.length > 5 && term.includes(n))) {
      return muscle;
    }
  }

  return null;
}
